def _normalize_query(q: str) -> str:
    """Strip whitespace and lowercase the query."""
    return q.strip().lower()


def _strip_phase_suffix(value: str) -> str:
    """Remove trailing phase markers like (aq), (s), (l), (g)."""
    return re.sub(r"\((aq|s|l|g)\)$", "", value.strip(), flags=re.IGNORECASE)


def _formula_signature(formula: str) -> Optional[str]:
    """Create canonical element-count signature for neutral formulas.

    Returns None when formula cannot be parsed with the neutral parser.
    """
    raw = _strip_phase_suffix(formula).replace(" ", "")
    if not raw:
        return None
    if any(ch in raw for ch in "+-^"):
        return None
    try:
        counts = parse_chemical_formula(raw)
    except ValueError:
        return None
    parts = []
    for element in sorted(counts.keys()):
        count = counts[element]
        parts.append(f"{element}{count if count != 1 else ''}")
    return "".join(parts)


def _substance_search_tokens(s: Substance) -> list[str]:
    """All searchable text tokens for a substance (lowercased)."""
    tokens = [
        s.id,
        s.name_da.lower(),
        s.formula.lower(),
    ]
    if s.name_en:
        tokens.append(s.name_en.lower())
    tokens.extend(syn.lower() for syn in s.synonyms)
    tokens.extend(tag.lower() for tag in s.tags)
    return tokens


def search_substances(query: str, database: list[Substance] = SUBSTANCES) -> list[Substance]:
    """Search substances by name, formula, synonym or tag.

    - Case-insensitive
    - Whitespace-trimmed
    - Returns exact matches first, then partial matches
    - Returns empty list if nothing found (no crash)
    """
    nq = _normalize_query(query)
    if not nq:
        return []

    nq_no_phase = _strip_phase_suffix(nq)
    nq_signature = _formula_signature(nq_no_phase)

    exact: list[Substance] = []
    partial: list[Substance] = []

    for s in database:
        tokens = _substance_search_tokens(s)
        formula_norm = _normalize_query(_strip_phase_suffix(s.formula))
        formula_signature = _formula_signature(s.formula)

        is_formula_exact = nq == formula_norm or nq_no_phase == formula_norm
        is_formula_equivalent = (
            nq_signature is not None
            and formula_signature is not None
            and nq_signature == formula_signature
        )

        if nq in tokens or is_formula_exact or is_formula_equivalent:
            exact.append(s)
        elif any(nq in tok for tok in tokens):
            partial.append(s)

    # Deduplicate while preserving order
    seen: set[str] = set()
    results: list[Substance] = []
    for s in exact + partial:
        if s.id not in seen:
            seen.add(s.id)
            results.append(s)
    return results


def get_substance_by_id(substance_id: str, database: list[Substance] = SUBSTANCES) -> Optional[Substance]:
    """Return a substance by its unique id, or None if not found."""
    for s in database:
        if s.id == substance_id:
            return s
    return None


