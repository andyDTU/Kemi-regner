_KW_25C = 1.0e-14

# Curated first/prototypical constants for common exam-relevant acids and bases.
# Values are representative at ~25 C and used as authoritative overrides.
_REFERENCE_PKA_BY_ID: dict[str, float] = {
    "hcl": -6.30,
    "hno3": -1.40,
    "h2so4": -3.00,
    "h3po4": 2.15,
    "ch3cooh": 4.76,
    "c2h5cooh": 4.87,
    "hf": 3.17,
    "h2co3": 6.35,
    "nh4_plus": 9.25,
}

_REFERENCE_PKB_BY_ID: dict[str, float] = {
    "naoh": -1.74,
    "koh": -1.74,
    "ca_oh_2": -1.74,
    "nh3": 4.74,
}


def _contains_any(value: str, terms: list[str]) -> bool:
    return any(term in value for term in terms)


def _infer_default_pka(s: Substance) -> float:
    if s.id in _REFERENCE_PKA_BY_ID:
        return _REFERENCE_PKA_BY_ID[s.id]

    meta = " ".join(
        filter(
            None,
            [
                s.id.lower(),
                s.formula.lower(),
                (s.subtype or "").lower(),
                (s.name_da or "").lower(),
                (s.name_en or "").lower(),
                " ".join(t.lower() for t in s.tags),
            ],
        )
    )

    if s.acid_strength == "stærk" or "stærk syre" in meta:
        return -1.0

    if _contains_any(meta, ["carboxyl", "cooh", "alkansyre", "eddikesyre", "propion"]):
        return 4.8

    if _contains_any(meta, ["phosphor", "fosfor", "h3po4"]):
        return 2.15

    if _contains_any(meta, ["kulsyre", "h2co3", "carbonic"]):
        return 6.35

    if _contains_any(meta, ["hydrofluoric", "flussyre", "hf"]):
        return 3.17

    return 4.75


def _infer_default_pkb(s: Substance) -> float:
    if s.id in _REFERENCE_PKB_BY_ID:
        return _REFERENCE_PKB_BY_ID[s.id]

    meta = " ".join(
        filter(
            None,
            [
                s.id.lower(),
                s.formula.lower(),
                (s.subtype or "").lower(),
                (s.name_da or "").lower(),
                (s.name_en or "").lower(),
                " ".join(t.lower() for t in s.tags),
            ],
        )
    )

    if s.base_strength == "stærk" or "stærk base" in meta or "hydroxid" in meta:
        return -1.74

    if _contains_any(meta, ["amin", "amine", "ammoniak", "ammonia", "nh3"]):
        return 4.0

    return 4.75


def _hydrate_acid_base_constants(database: list[Substance]) -> None:
    """Populate Ka/Kb/pKa/pKb for all acids and bases with internally consistent values."""
    for s in database:
        is_acid = s.category == "syre" or s.acid_base_role == "syre"
        is_base = s.category == "base" or s.acid_base_role == "base"

        if is_acid and s.pka is None:
            s.pka = _infer_default_pka(s)
        if is_base and s.pkb is None:
            s.pkb = _infer_default_pkb(s)

        if s.ka is None and s.pka is not None:
            s.ka = 10 ** (-s.pka)
        if s.kb is None and s.pkb is not None:
            s.kb = 10 ** (-s.pkb)

        if is_acid and s.ka is not None:
            if s.kb is None:
                s.kb = _KW_25C / s.ka
            if s.pkb is None and s.kb > 0:
                s.pkb = -math.log10(s.kb)

        if is_base and s.kb is not None:
            if s.ka is None:
                s.ka = _KW_25C / s.kb
            if s.pka is None and s.ka > 0:
                s.pka = -math.log10(s.ka)


_hydrate_acid_base_constants(SUBSTANCES)


