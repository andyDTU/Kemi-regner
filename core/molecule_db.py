"""
Molecule database: datamodel, dataset and search logic.

ADDING NEW SUBSTANCES
---------------------
Append a new Substance entry to SUBSTANCES at the bottom of this file.
All fields are optional except: id, name_da, formula, category, description.

CATEGORIES (use one primary category in `category`):
  syre | base | salt | ion | molekyle | oxid | organisk | andet

SUBTYPES: stærk syre | svag syre | stærk base | svag base | basisk oxid |
          sur oxid | amfoter oxid | binær salt | neutralt salt | ...

FIELD DOCS (all Optional unless noted):
  id            (str, required) unique slug, e.g. "hcl"
  name_da       (str, required) primary Danish name
  name_en       (str)           English name
  formula       (str, required) chemical formula as typed
  category      (str, required) see CATEGORIES above
  subtype       (str)           finer classification
  description   (str, required) 1-2 sentence Danish description
  synonyms      (list[str])    alternative names / common aliases
  tags          (list[str])    searchable keywords
  molar_mass    (float)         g/mol
  acid_base_role (str)         "syre" | "base" | "amfoter" | "neutral"
  acid_strength (str)          "stærk" | "svag"
  base_strength (str)          "stærk" | "svag"
  ion_charge    (int)           e.g. -1, +2
  physical_state (str)         "fast" | "flydende" | "gas" | "vandig opløsning"
  polarity      (str)          "polar" | "upolar"
  solubility_note (str)        kort note om opløselighed
  conjugate_acid (str)         formel for konjugeret syre
  conjugate_base (str)         formel for konjugeret base
    ka            (float)         syrekonstant (forste/prototypisk dissociation)
    kb            (float)         basekonstant (forste/prototypisk protonoptag)
    pka           (float)         -log10(Ka)
    pkb           (float)         -log10(Kb)
  salt_components (list[str])  ioner i saltet, e.g. ["Na+", "Cl-"]
  common_exam_note (str)       eksamensrelevant note
"""

