def _normalize_formula_for_vsepr(formula: str) -> str:
    """Normalize formula for VSEPR lookup."""
    return _strip_phase_suffix(formula).replace(" ", "")


def _is_monatomic_species(formula: str) -> bool:
    """Return True for monatomic atom/ion formulas like Cl-, Na+, Fe3+."""
    return bool(re.fullmatch(r"[A-Z][a-z]?(?:\d+)?[+-]?", formula))


def _is_diatomic_species(formula: str) -> bool:
    """Return True for neutral diatomic molecules like O2, N2, Cl2."""
    if any(ch in formula for ch in "^+-"):
        return False
    m = re.fullmatch(r"([A-Z][a-z]?)(\d+)", formula)
    if not m:
        return False
    return m.group(2) == "2"


def get_vsepr_description(s: Substance) -> str:
    """Return a VSEPR-style structure description for a substance."""
    if s.vsepr_structure:
        return s.vsepr_structure

    formula = _normalize_formula_for_vsepr(s.formula)
    if formula in _VSEPR_OVERRIDES:
        return _VSEPR_OVERRIDES[formula]

    if s.category == "salt":
        return "Ionisk gitter i fast fase; VSEPR anvendes primart pa eventuelle polyatomiske ioner"

    if _is_monatomic_species(formula):
        return "Monatomisk partikel (ingen VSEPR-geometri)"

    if _is_diatomic_species(formula):
        return "Diatomisk lineaer"

    if s.category in {"organisk", "molekyle", "oxid", "syre", "base", "ion"}:
        return "Kompleks/flercenter-struktur; se Lewis-struktur for lokal VSEPR omkring centrale atomer"

    return "Ingen VSEPR-oplysning tilgaengelig"


def get_vsepr_distortion_label(s: Substance) -> str:
    """Classify tetrahedral geometry as distorted/nondistorted when possible.

    Returns one of:
    - "Tetraedrisk nondistorted"
    - "Tetraedrisk distorted"
    - "Ikke tetraedrisk / ikke entydigt"
    """
    desc = get_vsepr_description(s).lower()

    # Most explicit and reliable path: AX notation in the descriptor.
    if "ax4" in desc and "tetra" in desc:
        return "Tetraedrisk nondistorted"
    if ("ax3e" in desc or "ax2e2" in desc) and ("pyramidal" in desc or "vinklet" in desc or "tetra" in desc):
        return "Tetraedrisk distorted"

    # Fallback text-based cues when AX notation is not present.
    if "tetra" in desc:
        if "omkring" in desc or "polyatomiske ioner" in desc:
            return "Tetraedrisk (lokal)"
        return "Tetraedrisk nondistorted"
    if "pyramidal" in desc or "vinklet" in desc:
        return "Tetraedrisk distorted"

    return "Ikke tetraedrisk / ikke entydigt"

